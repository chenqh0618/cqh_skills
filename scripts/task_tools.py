#!/usr/bin/env python3
"""Small, local task catalogue and reversible archive moves; Python 3.11+."""
import argparse
import fcntl
import json
import os
from pathlib import Path
import re
import tempfile
from datetime import datetime
from urllib.parse import quote
import tomllib


STATES = {"planned", "running", "completed", "failed", "archived", "unknown"}
HOSTS = {"codex", "claude"}
UNIT = re.compile(r"^([AE])(\d+)_.+$")
META = re.compile(r"^```toml\n(.*?)^```[ \t]*$", re.M | re.S)
GENERATED = "<!-- generated by project-init-loose; edit task ABSTRACTs, then rebuild -->"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def task_id(value):
    match = re.fullmatch(r"([AE])(\d+)", value)
    require(match is not None and int(match[2]) > 0, f"Invalid task ID: {value}")
    return f"{match[1]}{int(match[2]):02d}"


def timestamp():
    return datetime.now().astimezone().isoformat(timespec="seconds")


def scalar(value):
    require(isinstance(value, (str, int, bool, list)), "Unsupported metadata value")
    if isinstance(value, list):
        require(all(isinstance(x, str) for x in value), "Metadata lists must contain strings")
    return json.dumps(value, ensure_ascii=False)


def metadata_text(data):
    rows = []
    for key, value in data.items():
        require(re.fullmatch(r"[a-z_]+", key), f"Invalid metadata key: {key}")
        if not isinstance(value, dict):
            rows.append(f"{key} = {scalar(value)}")
    for key, value in data.items():
        if isinstance(value, dict):
            require(key == "archive", f"Unsupported metadata table: {key}")
            rows.extend(["", "[archive]"])
            for field, item in value.items():
                require(re.fullmatch(r"[a-z_]+", field), f"Invalid archive key: {field}")
                rows.append(f"{field} = {scalar(item)}")
    return "\n".join(rows)


def atomic_write(path, text):
    require(not path.is_symlink(), f"Refusing symlink: {path}")
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent,
                                     prefix=".loose-", delete=False) as out:
        temporary = Path(out.name)
        try:
            out.write(text)
            out.flush()
            os.fsync(out.fileno())
            os.chmod(temporary, path.stat().st_mode & 0o777 if path.exists() else 0o644)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def validate_metadata(data, ident, archived, path):
    for field in ("id", "status", "created_at", "created_by", "first_executed_by"):
        require(isinstance(data.get(field), str), f"{path}: missing/string field {field}")
    require(data["id"] == ident, f"{path}: metadata ID disagrees with directory ({ident})")
    require(data["status"] in STATES, f"{path}: invalid status")
    require((data["status"] == "archived") == archived, f"{path}: status/location disagree")
    require(data["created_by"] in HOSTS | {"unknown"}, f"{path}: invalid created_by")
    require(data["first_executed_by"] in HOSTS | {"unknown", "pending"},
            f"{path}: invalid first_executed_by")
    upstream = data.get("upstream")
    require(isinstance(upstream, list) and all(isinstance(x, str) for x in upstream),
            f"{path}: upstream must be an array of local task IDs")
    require(all(task_id(x) == x and x != ident for x in upstream), f"{path}: invalid upstream ID")
    require(len(set(upstream)) == len(upstream), f"{path}: duplicate upstream IDs")
    if archived:
        archive = data.get("archive", {})
        for field in ("original_path", "original_root", "archived_at", "reason", "previous_status", "retention"):
            require(isinstance(archive.get(field), str) and archive[field],
                    f"{path}: missing archive.{field}")
        require(archive["previous_status"] in {"planned", "completed", "failed"},
                f"{path}: invalid archive.previous_status")


def read_unit(path, side, archived):
    match = UNIT.fullmatch(path.name)
    require(match[1] == ("A" if side == "analysis" else "E"), f"Wrong task side: {path}")
    ident = task_id(match[1] + match[2])
    abstract = path / "ABSTRACT.md"
    require(not abstract.is_symlink(), f"Refusing linked metadata: {abstract}")
    data, text = None, ""
    if abstract.exists():
        text = abstract.read_text(encoding="utf-8")
        blocks = list(META.finditer(text))
        require(len(blocks) == 1, f"{abstract}: expected exactly one TOML metadata block")
        data = tomllib.loads(blocks[0][1])
        validate_metadata(data, ident, archived, abstract)
    else:
        require(not archived, f"Archived task lacks ABSTRACT: {path}")
    return {"id": ident, "path": path, "side": side, "archived": archived,
            "data": data, "text": text}


def scan(root):
    units = {}
    for base in (root, root / "_archived"):
        require(not base.is_symlink(), f"Refusing linked task container: {base}")
        for side in ("analysis", "explore"):
            folder = base / side
            require(folder.is_dir() and not folder.is_symlink(), f"Missing or linked task container: {folder}")
            for path in sorted(folder.iterdir()):
                if not UNIT.fullmatch(path.name):
                    continue
                require(path.is_dir() and not path.is_symlink(), f"Invalid or linked task directory: {path}")
                item = read_unit(path, side, base != root)
                require(item["id"] not in units, f"Duplicate task ID: {item['id']}")
                units[item["id"]] = item
    for item in units.values():
        if item["data"] is not None:
            missing = set(item["data"]["upstream"]) - units.keys()
            require(not missing, f"{item['id']}: unresolved upstream IDs: {sorted(missing)}")
    return units


def update_metadata(item, data):
    text = META.sub(lambda _: "```toml\n" + metadata_text(data) + "\n```", item["text"], count=1)
    atomic_write(item["path"] / "ABSTRACT.md", text)
    item.update(data=data, text=text)


def check_indexes(root):
    for path in (root / "TASKS.md", root / "_archived/INDEX.md"):
        require(not path.is_symlink(), f"Refusing linked index: {path}")
        if path.exists():
            require(GENERATED in path.read_text(encoding="utf-8"), f"Not a generated index: {path}")


def index_text(root, units, archived):
    title = "历史任务" if archived else "活跃区任务（含已完成，排除归档）"
    rows = [f"# {title}", "", GENERATED, "", "以任务本地 ABSTRACT 为准；legacy 表示尚未补元数据。", "",
            "| ID | 任务 | 状态 | 问题 | 入口 |", "|---|---|---|---|---|"]
    base = root / "_archived" if archived else root
    for item in sorted(units.values(), key=lambda x: (x["id"][0], int(x["id"][1:]))):
        if item["archived"] != archived:
            continue
        data = item["data"]
        state = data["status"] if data else "legacy"
        question = re.search(r"^## 问题与范围\s*\n+([^\n]+)", item["text"], re.M)
        question = question[1].strip() if question else "待补摘要"
        destination = item["path"] / ("ABSTRACT.md" if data else "SUMMARY.md")
        if not destination.exists():
            destination = item["path"]
        link = quote(destination.relative_to(base).as_posix())
        values = [item["id"], item["path"].name, state, question]
        values = [v.replace("|", "\\|").replace("\n", " ") for v in values]
        rows.append("| " + " | ".join(values) + f" | [读取]({link}) |")
    return "\n".join(rows) + "\n"


def rebuild_indexes(root):
    check_indexes(root)
    units = scan(root)
    atomic_write(root / "TASKS.md", index_text(root, units, False))
    atomic_write(root / "_archived/INDEX.md", index_text(root, units, True))


def get_unit(units, ident):
    ident = task_id(ident)
    require(ident in units, f"Unknown task ID: {ident}")
    item = units[ident]
    require(item["data"] is not None, f"{ident}: add factual ABSTRACT metadata using .project/MIGRATION.md first")
    return item


def create(root, units, args):
    require(re.fullmatch(r"[a-z][A-Za-z0-9]*", args.name), "Use camelCase with letters and digits")
    require(args.question.strip() and "\n" not in args.question, "Provide a one-line task question")
    prefix = "A" if args.side == "analysis" else "E"
    number = max([int(x[1:]) for x in units if x.startswith(prefix)] or [0]) + 1
    ident = f"{prefix}{number:02d}"
    upstream = [task_id(x) for x in args.upstream]
    require(set(upstream) <= units.keys(), "Unknown upstream task ID")
    require(len(set(upstream)) == len(upstream), "Duplicate upstream IDs")
    title = f"{ident}_{args.name}_{datetime.now().strftime('%m%d')}_{args.agent}"
    path = root / args.side / title
    data = {"id": ident, "status": "planned", "created_at": timestamp(), "created_by": args.agent,
            "first_executed_by": "pending", "upstream": upstream}
    rendered = {}
    for filename in ("ABSTRACT.md", "SUMMARY.md", "AS_RUN.md"):
        template = (root / ".project/templates" / filename).read_text(encoding="utf-8")
        # Replace template tokens once so user text cannot introduce a second substitution.
        values = {"TITLE": title, "META": metadata_text(data), "QUESTION": args.question.strip()}
        rendered[filename] = re.sub(r"\{\{(TITLE|META|QUESTION)\}\}", lambda m: values[m[1]], template)
    require(not path.exists() and not path.is_symlink(), f"Task destination exists: {path}")
    with tempfile.TemporaryDirectory(prefix=".new-task-", dir=root / args.side) as temporary:
        stage = Path(temporary) / title
        stage.mkdir()
        for directory in ("scripts", "logs", "results"):
            (stage / directory).mkdir()
        for filename, text in rendered.items():
            (stage / filename).write_text(text, encoding="utf-8")
        read_unit(stage, args.side, False)
        os.rename(stage, path)
    return {"created": ident, "path": str(path)}


def transition(root, units, args):
    item = get_unit(units, args.id)
    data = dict(item["data"])
    if args.command in {"start", "finish"}:
        require(not item["archived"], "Restore this task before execution")
        if args.command == "start":
            cold = [x for x in data["upstream"] if units[x]["archived"]]
            require(not cold, f"Restore computational inputs first: {cold}")
            data["status"] = "running"
            if data["first_executed_by"] == "pending":
                data["first_executed_by"] = args.agent
        else:
            require(data["status"] == "running" or args.status == "failed",
                    "Record the actual start before marking completed")
            data["status"] = args.status
        update_metadata(item, data)
        return {"id": item["id"], "status": data["status"]}

    source = item["path"]
    if args.command == "archive":
        require(not item["archived"], "Task is already archived")
        require(data["status"] in {"planned", "completed", "failed"},
                "Archive only stopped tasks with a known status; running/unknown is not eligible")
        require(args.reason.strip() and "\n" not in args.reason, "Provide a one-line archive reason")
        blockers = [x["id"] for x in units.values() if x["data"] is not None
                    and x["data"]["status"] in {"planned", "running"}
                    and item["id"] in x["data"]["upstream"]]
        require(not blockers, f"Active computational dependants: {blockers}")
        replacement = task_id(args.replacement) if args.replacement else ""
        require(not replacement or replacement in units and replacement != item["id"], "Invalid replacement ID")
        destination = root / "_archived" / item["side"] / source.name
        data["archive"] = {"original_path": source.relative_to(root).as_posix(), "original_root": str(root),
                           "archived_at": timestamp(), "reason": args.reason.strip(), "replacement": replacement,
                           "previous_status": data["status"],
                           "retention": data.get("archive", {}).get("retention", "intact; no cleanup performed")}
        data["status"] = "archived"
    else:
        require(item["archived"], "Task is not archived")
        archive = dict(data["archive"])
        expected = f"{item['side']}/{source.name}"
        require(archive["original_path"] == expected, "Archive original_path disagrees with task identity")
        require(archive["original_root"] == str(root), "Project root changed; review historical absolute paths before restore")
        destination = root / expected
        data["status"] = archive["previous_status"]
        archive["restored_at"] = timestamp()
        data["archive"] = archive
    require(not destination.exists() and not destination.is_symlink(), f"Destination already exists: {destination}")
    require(source.stat().st_dev == destination.parent.stat().st_dev,
            "Cross-filesystem move refused; prepare a separate verified migration")
    report = {"operation": args.command, "source": str(source), "destination": str(destination),
              "apply": args.apply, "retention": data["archive"]["retention"]}
    if args.command == "archive":
        report["check_required"] = "Verify writers and unregistered/external dependencies; --checked attests to that check"
        report["legacy_tasks"] = [x["id"] for x in units.values() if x["data"] is None]
    if not args.apply:
        return report
    if args.command == "archive":
        require(args.checked, "Complete writer/dependency checks, then use --apply --checked")
    old_text = item["text"]
    os.rename(source, destination)
    item["path"] = destination
    try:
        update_metadata(item, data)
    except Exception:
        # atomic_write failures normally leave the old metadata intact. Restore
        # location first: rollback must still work when the disk has no space.
        require(not source.exists() and not source.is_symlink(), f"Rollback source appeared: {source}")
        os.rename(destination, source)
        item["path"] = source
        if (source / "ABSTRACT.md").read_text(encoding="utf-8") != old_text:
            atomic_write(source / "ABSTRACT.md", old_text)
        raise
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parent.parent)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("index", help="Rebuild current and archived catalogues")
    new = sub.add_parser("new", help="Create a task for an already-authorized scientific objective")
    new.add_argument("side", choices=("analysis", "explore"))
    new.add_argument("name", help="camelCase task content")
    new.add_argument("--agent", required=True, choices=sorted(HOSTS))
    new.add_argument("--question", required=True)
    new.add_argument("--upstream", nargs="*", default=[])
    start = sub.add_parser("start", help="Record actual execution start; does not launch a job")
    start.add_argument("id")
    start.add_argument("--agent", required=True, choices=sorted(HOSTS))
    finish = sub.add_parser("finish")
    finish.add_argument("id")
    finish.add_argument("--status", required=True, choices=("completed", "failed"))
    for command in ("archive", "restore"):
        child = sub.add_parser(command, help="Preview by default; --apply performs a reversible move")
        child.add_argument("id")
        mode = child.add_mutually_exclusive_group()
        mode.add_argument("--apply", action="store_true")
        mode.add_argument("--dry-run", action="store_true")
        if command == "archive":
            child.add_argument("--reason", required=True)
            child.add_argument("--replacement")
            child.add_argument("--checked", action="store_true")
    args = parser.parse_args()
    root = args.project.resolve()
    try:
        control = root / ".project"
        require(control.is_dir() and not control.is_symlink(), "Missing or linked .project directory")
        lock = control / "tasks.lock"
        require(not lock.is_symlink(), "Refusing linked lock file")
        with lock.open("a") as handle:
            fcntl.flock(handle, fcntl.LOCK_EX)
            units = scan(root)
            mutates = args.command not in {"archive", "restore"} or args.apply
            if mutates:
                check_indexes(root)
            if args.command == "new":
                report = create(root, units, args)
            elif args.command == "index":
                report = {"indexed": len(units)}
            else:
                report = transition(root, units, args)
            if mutates:
                rebuild_indexes(root)
            print(json.dumps(report, ensure_ascii=False, indent=2))
    except (ValueError, OSError) as error:
        parser.exit(2, f"ERROR: {error}\n")


if __name__ == "__main__":
    main()
